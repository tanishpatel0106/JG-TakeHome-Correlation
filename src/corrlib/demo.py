"""Deterministic synthetic demo dataset: ``python -m corrlib.demo --out data/demo``.

Writes, under ``--out``::

    demo_stock_data.zip                 320 daily files x ~300 tickers (zip comment marks it synthetic)
    updates/append/<YYYYMMDD>.csv       the next business day after the last date
    updates/correction/<YYYYMMDD>.csv   an existing mid-sample date with one price corrected
    overrides.example.json              confirms the two detected uniform-price days

Everything is generated from a fixed seed, so the files are byte-identical on
every run. The data is clearly synthetic (tickers such as ``TEC07``) and is
built to exercise every rule of the pipeline:

* sector factor structure (six sectors of 40 names: clearly positive
  intra-sector correlations, ~0.7), a market factor, 55 idiosyncratic names
  (near-zero correlations) and an inverse pair ``INVA``/``INVB`` (~ -0.9);
* the real-looking ticker ``NA`` (must stay a string), a constant-price ticker
  ``FLAT`` (zero variance: ``constant_returns``);
* empty and non-numeric prices, one missing row, one duplicate row, one file
  whose ``Date`` column is ``M/D/YYYY``;
* a late listing (``LATE``) and a delisting (``GONE``);
* a uniform 20.0 seed day first, a placeholder day (every price 1.0) and a
  re-base day (every price 20.0 after a three-week calendar gap);
* a fat-finger price (``TEC07`` x 1.35 on the correction date) that the
  correction file fixes.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import zipfile
from dataclasses import dataclass
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

from .config import DEMO_ZIP_COMMENT

log = logging.getLogger("corrlib.demo")

DEMO_SEED = 20240906
DEMO_ZIP_NAME = "demo_stock_data.zip"
DEMO_MEMBER_DIR = "demo_stock_data"
START = "2023-01-02"

#: Business days in the zip; the append file is day N_DAYS.
N_DAYS = 320
SECTORS: tuple[str, ...] = ("TEC", "FIN", "NRG", "HLT", "CON", "IND")
PER_SECTOR = 40
N_IDIOSYNCRATIC = 55

# Day indices of the planted features.
MDY_DAY = 30
DUPLICATE_DAY = 45
MISSING_ROW_DAY = 88
CORRECTION_DAY = 90
LISTING_DAY = 100
PLACEHOLDER_DAY = 130
REBASE_DAY = 210
DELISTING_DAY = 240
#: Business days skipped just before the re-base day (the calendar gap).
GAP_BUSINESS_DAYS = 15

CORRECTION_TICKER = "TEC07"
FAT_FINGER = 1.35
#: (day, ticker, price text) cells written with a bad price.
BAD_PRICES: tuple[tuple[int, str, str], ...] = (
    (57, "TEC05", ""),
    (63, "FIN12", "n/a"),
    (150, "HLT03", "abc"),
    (260, "CON09", ""),
)
MISSING_ROW = (MISSING_ROW_DAY, "IDI07")
DUPLICATE_ROW = (DUPLICATE_DAY, "CON10")

README = """Synthetic demo data generated by `python -m corrlib.demo` (seed {seed}).
NOT real market data. Tickers, prices and correlations are simulated.
"""


@dataclass(frozen=True)
class DemoFiles:
    """Paths written by :func:`generate_demo` and the facts the data was planted with."""

    out_dir: Path
    zip_path: Path
    append_csv: Path
    correction_csv: Path
    overrides_path: Path
    dates: list[date]
    append_date: date
    tickers: list[str]
    placeholder_date: date
    rebase_date: date
    correction_date: date
    correction_ticker: str
    correct_price: float
    zip_price: float


def demo_tickers() -> list[str]:
    """The demo universe in sector order (``NA`` replaces ``FIN40``)."""
    names: list[str] = []
    for g in range(len(SECTORS)):
        for k in range(1, PER_SECTOR + 1):
            names.append(f"{SECTORS[g]}{k:02d}")
    names[names.index("FIN40")] = "NA"
    for k in range(1, N_IDIOSYNCRATIC + 1):
        names.append(f"IDI{k:02d}")
    names.extend(["INVA", "INVB", "FLAT", "LATE", "GONE"])
    return names


def demo_calendar() -> list[date]:
    """``N_DAYS + 1`` business days (the last one is the append day), with a gap before the re-base."""
    days = list(pd.bdate_range(START, periods=N_DAYS + 1 + GAP_BUSINESS_DAYS).date)
    return days[:REBASE_DAY] + days[REBASE_DAY + GAP_BUSINESS_DAYS :]


def demo_prices(seed: int = DEMO_SEED) -> tuple[list[str], np.ndarray, np.ndarray]:
    """True prices of the demo universe for ``N_DAYS + 1`` days.

    Returns
    -------
    (tickers, prices, listed)
        ``prices`` float64 ``[T+1 x N]`` (the market path, before any planted
        defect; day 0 and the re-base day are exactly 20.0), ``listed`` bool
        ``[T+1 x N]`` (False before ``LATE`` lists and after ``GONE`` delists).
    """
    rng = np.random.default_rng(seed)
    tickers = demo_tickers()
    n_days, n = N_DAYS + 1, len(tickers)
    col: dict[str, int] = {}
    for j in range(n):
        col[tickers[j]] = j

    # Daily log-return volatilities: intra-sector rho ~ (0.25 * 0.006^2 + 0.016^2) /
    # (0.25 * 0.006^2 + 0.016^2 + 0.010^2) ~ 0.73; across sectors ~ 0.02.
    market = rng.normal(0.0, 0.006, n_days)
    sector = rng.normal(0.0, 0.016, (n_days, len(SECTORS)))
    noise = rng.normal(0.0, 0.010, (n_days, n))
    inverse = rng.normal(0.0, 0.015, n_days)

    n_sector = len(SECTORS) * PER_SECTOR
    member_of = np.repeat(np.arange(len(SECTORS)), PER_SECTOR)
    r = np.zeros((n_days, n))
    r[:, :n_sector] = 0.5 * market[:, None] + sector[:, member_of] + noise[:, :n_sector]
    idio = np.arange(n_sector, n_sector + N_IDIOSYNCRATIC)
    r[:, idio] = 1.5 * noise[:, idio]
    r[:, col["INVA"]] = inverse + 0.4 * noise[:, col["INVA"]]
    r[:, col["INVB"]] = -inverse + 0.4 * noise[:, col["INVB"]]
    r[:, col["LATE"]] = 0.5 * market + sector[:, SECTORS.index("IND")] + noise[:, col["LATE"]]
    r[:, col["GONE"]] = 0.5 * market + sector[:, SECTORS.index("FIN")] + noise[:, col["GONE"]]
    r[:, col["FLAT"]] = 0.0
    r[0] = 0.0

    # Log prices restart at 20.0 on day 0 and on the re-base day; LATE lists at 35.0.
    cum = np.cumsum(r, axis=0)
    log_p = np.empty_like(cum)
    starts = (0, REBASE_DAY, n_days)
    for k in range(len(starts) - 1):
        a, b = starts[k], starts[k + 1]
        log_p[a:b] = np.log(20.0) + cum[a:b] - cum[a]
    late = col["LATE"]
    log_p[LISTING_DAY:REBASE_DAY, late] = (
        np.log(35.0) + cum[LISTING_DAY:REBASE_DAY, late] - cum[LISTING_DAY, late]
    )
    prices = np.exp(log_p)
    prices[0] = 20.0
    prices[REBASE_DAY] = 20.0

    listed = np.ones((n_days, n), dtype=bool)
    listed[:LISTING_DAY, late] = False
    listed[DELISTING_DAY + 1 :, col["GONE"]] = False
    return tickers, prices, listed


def _daily_csv(
    day: date, tickers: np.ndarray, price_text: np.ndarray, mdy: bool = False
) -> bytes:
    """CSV bytes (``Ticker,Date,Price``, CRLF line ends like the source data)."""
    text = f"{day.month}/{day.day}/{day.year}" if mdy else day.isoformat()
    rows = np.char.add(np.char.add(np.char.add(tickers.astype(str), ","), text + ","), price_text)
    return ("Ticker,Date,Price\r\n" + "\r\n".join(rows.tolist()) + "\r\n").encode("utf-8")


def _written_day(
    t: int, day: date, tickers: list[str], prices: np.ndarray, listed: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """Ticker and price-text columns of day ``t`` as written to the zip (defects planted)."""
    names = np.array(tickers)
    values = prices[t].copy()
    if t == PLACEHOLDER_DAY:
        values[:] = 1.0
    text = np.char.mod("%.4f", values)
    if t == CORRECTION_DAY:
        j = tickers.index(CORRECTION_TICKER)
        text[j] = f"{prices[t, j] * FAT_FINGER:.4f}"
    for k in range(len(BAD_PRICES)):
        if BAD_PRICES[k][0] == t:
            text[tickers.index(BAD_PRICES[k][1])] = BAD_PRICES[k][2]
    keep = listed[t].copy()
    if t == MISSING_ROW[0]:
        keep[tickers.index(MISSING_ROW[1])] = False
    names, text = names[keep], text[keep]
    if t == DUPLICATE_ROW[0]:
        j = int(np.flatnonzero(names == DUPLICATE_ROW[1])[0])
        names = np.append(names, names[j])
        text = np.append(text, text[j])
    return names, text


def generate_demo(out_dir: str | Path, seed: int = DEMO_SEED) -> DemoFiles:
    """Write the demo zip, the two update files and the example overrides under ``out_dir``.

    Deterministic: the same ``seed`` gives byte-identical files (fixed zip
    timestamps and member order).
    """
    out_dir = Path(out_dir)
    tickers, prices, listed = demo_prices(seed)
    calendar = demo_calendar()
    dates, append_date = calendar[:N_DAYS], calendar[N_DAYS]

    out_dir.mkdir(parents=True, exist_ok=True)
    zip_path = out_dir / DEMO_ZIP_NAME
    with zipfile.ZipFile(zip_path, "w") as zf:
        zf.comment = DEMO_ZIP_COMMENT.encode("utf-8")
        _add(zf, f"{DEMO_MEMBER_DIR}/README.txt", README.format(seed=seed).encode("utf-8"))
        for t in range(N_DAYS):
            names, text = _written_day(t, dates[t], tickers, prices, listed)
            data = _daily_csv(dates[t], names, text, mdy=t == MDY_DAY)
            _add(zf, f"{DEMO_MEMBER_DIR}/{dates[t].strftime('%Y%m%d')}.csv", data)

    append_dir = out_dir / "updates" / "append"
    correction_dir = out_dir / "updates" / "correction"
    append_dir.mkdir(parents=True, exist_ok=True)
    correction_dir.mkdir(parents=True, exist_ok=True)
    stale = sorted(append_dir.glob("*.csv")) + sorted(correction_dir.glob("*.csv"))
    for k in range(len(stale)):
        stale[k].unlink()

    names, text = _written_day(N_DAYS, append_date, tickers, prices, listed)
    append_csv = append_dir / f"{append_date.strftime('%Y%m%d')}.csv"
    append_csv.write_bytes(_daily_csv(append_date, names, text))

    correction_date = dates[CORRECTION_DAY]
    names, text = _written_day(CORRECTION_DAY, correction_date, tickers, prices, listed)
    j = tickers.index(CORRECTION_TICKER)
    correct = f"{prices[CORRECTION_DAY, j]:.4f}"
    text[int(np.flatnonzero(names == CORRECTION_TICKER)[0])] = correct
    correction_csv = correction_dir / f"{correction_date.strftime('%Y%m%d')}.csv"
    correction_csv.write_bytes(_daily_csv(correction_date, names, text))

    overrides_path = out_dir / "overrides.example.json"
    overrides = {
        "overrides": [
            {
                "date": dates[PLACEHOLDER_DAY].isoformat(),
                "classification": "placeholder",
                "reason": "Demo: the data vendor confirmed that the 1.0 prices on this date are fill-ins.",
                "author": "demo-operator",
            },
            {
                "date": dates[REBASE_DAY].isoformat(),
                "classification": "rebase",
                "reason": "Demo: the vendor re-based every series to 20.0 after the data outage.",
                "author": "demo-operator",
            },
        ]
    }
    overrides_path.write_text(json.dumps(overrides, indent=2) + "\n", encoding="utf-8")

    return DemoFiles(
        out_dir=out_dir,
        zip_path=zip_path,
        append_csv=append_csv,
        correction_csv=correction_csv,
        overrides_path=overrides_path,
        dates=dates,
        append_date=append_date,
        tickers=tickers,
        placeholder_date=dates[PLACEHOLDER_DAY],
        rebase_date=dates[REBASE_DAY],
        correction_date=correction_date,
        correction_ticker=CORRECTION_TICKER,
        correct_price=float(correct),
        zip_price=round(float(prices[CORRECTION_DAY, j] * FAT_FINGER), 4),
    )


def _add(zf: zipfile.ZipFile, name: str, data: bytes) -> None:
    """Add a member with a fixed timestamp (so the zip bytes are reproducible)."""
    info = zipfile.ZipInfo(name, date_time=(2024, 1, 1, 0, 0, 0))
    info.compress_type = zipfile.ZIP_DEFLATED
    info.external_attr = 0o644 << 16
    zf.writestr(info, data)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m corrlib.demo", description="Write the synthetic demo dataset.")
    parser.add_argument("--out", type=Path, default=Path("data/demo"), help="output directory (default: %(default)s)")
    parser.add_argument("--seed", type=int, default=DEMO_SEED, help="random seed (default: %(default)s)")
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)-7s %(name)s: %(message)s", datefmt="%H:%M:%S")
    files = generate_demo(args.out, seed=args.seed)
    print(f"Synthetic demo data -> {files.out_dir}")
    print(f"  zip          {files.zip_path} ({len(files.dates)} dates x {len(files.tickers)} tickers, "
          f"{files.dates[0]} .. {files.dates[-1]})")
    print(f"  append       {files.append_csv} (next business day {files.append_date})")
    print(f"  correction   {files.correction_csv} ({files.correction_ticker}: {files.zip_price} -> {files.correct_price})")
    print(f"  overrides    {files.overrides_path}")
    print(f"  planted      placeholder {files.placeholder_date}, re-base {files.rebase_date} (after a calendar gap)")
    print(f"Next: python -m corrlib.build --zip {files.zip_path} --out {files.out_dir / 'store'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
